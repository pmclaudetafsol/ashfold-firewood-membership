/**
 * Build the eight draft-status deliveries for a member who has just joined,
 * spaced roughly five weeks apart starting three weeks after sign-up. Used
 * only by the registration wizard — every other demo delivery is seeded data.
 */
export function createSeasonDeliveries(params: {
  customerId: string;
  customerName: string;
  area: string;
  postcode: string;
  town: string;
  crates: number;
  volumeM3: number;
  instructions?: string;
  startDate: Date;
}): Delivery[] {
  const { customerId, customerName, area, postcode, town, crates, volumeM3, instructions, startDate } = params;

  return Array.from({ length: 8 }).map((_, index) => {
    const date = new Date(startDate);
    date.setUTCDate(date.getUTCDate() + 21 + index * 37);
    const scheduledDate = date.toISOString().slice(0, 10);

    return {
      id: `del-new-${customerId}-${index + 1}`,
      sequence: index + 1,
      customerId,
      customerName,
      area,
      postcode,
      town,
      scheduledDate,
      window: index % 2 === 0 ? '08:00 – 12:00' : '12:00 – 16:00',
      status: 'draft',
      crates,
      volumeM3,
      supplierId: null,
      supplierName: null,
      driver: null,
      instructions,
      operationalNotes: 'Provisional slot created at sign-up. Confirmed nearer the date.',
      deliveredAt: null,
      timeline: [
        {
          id: `ev-new-${customerId}-${index + 1}`,
          at: new Date().toISOString(),
          label: 'Draft',
          detail: 'Added to your season plan at sign-up.',
        },
      ],
    };
  });
}
